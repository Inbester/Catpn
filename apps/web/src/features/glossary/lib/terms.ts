/** Characters that should not stop a word from matching an entry. */
const TRIM = /^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu;

export function normalise(word: string): string {
  return word.replace(TRIM, '').toLowerCase();
}

/**
 * Look a word up, trying the two-word phrase around it first.
 *
 * "profit factor" and "risk of ruin" mean something the separate words do
 * not, so the phrase wins when there is one.
 */
export function lookup(word: string, before = '', after = ''): Term | null {
  const one = normalise(word);
  if (!one) return null;

  const left = normalise(before);
  const right = normalise(after);

  const candidates = [
    left && right ? `${left} ${one} ${right}` : '',
    right ? `${one} ${right}` : '',
    left ? `${left} ${one}` : '',
    one,
  ].filter(Boolean);

  for (const candidate of candidates) {
    const found = TERMS[candidate];
    if (found) return found;
  }
  return null;
}
